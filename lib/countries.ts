// Validate/normalise a raw country string to a picker-supported flag code,
// or null. The picker accepts lowercase alpha-2 (and gb-* home nations).
export function normalizeCountry(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const c = raw.trim().toLowerCase();
  if (!/^[a-z]{2}(-[a-z]{3})?$/.test(c)) return null;
  return COUNTRIES.some((x) => x.code === c) ? c : null;
}
